(** * Outputs for the counter: the XState module and its test oracle.

    [counter_js] is the printed machine.  [counter_oracle] is computed from
    the app's [update], [enabled], and [enc] in Counter.v and
    CounterMachine.v, not from the printed machine, so the Node test checks
    XState against the specification:

    - [steps]: sampled states (both control states, counts around every
      boundary) times sampled events (amounts around the cap), with the
      expected next snapshot, meta, and [snapshot.can];
    - [traces]: pseudo-random event sequences from [initial], with the
      expected snapshot after every event;
    - [schema]: the payload schema of each event type and [payload_max],
      for the payload tests.

    Every event in [steps] and [traces] passes its schema
    ([oracle_events_admitted]), so by [js_step_correct] the expected
    snapshots are also what [js_step] gives. *)

From Stdlib Require Import String List NArith.
From VerifiedListUI Require Import XState XStateCtx CtxJs Counter CounterMachine Json.
Import ListNotations.
Open Scope list_scope.
Open Scope string_scope.

Definition counter_js : string :=
  js_module "Generated by Rocq from theories/CounterMachine.v (printer: theories/CtxJs.v). Do not edit."
    counter.

(** ** JSON encodings *)

Definition snap_json (st : snapshot) : json :=
  JObj [("value", JStr (fst st));
        ("context", JObj (map (fun kv => (fst kv, JNum (snd kv))) (snd st)))].

Definition event_json (e : event) : json :=
  match e with
  | Add n | Sub n => JObj [("type", JStr (fst (ev e))); ("n", JNum n)]
  | _ => JObj [("type", JStr (fst (ev e)))]
  end.

(** ** Sampled steps *)

Definition sample_counts : list nat :=
  [0; 1; 9; 10; 99; 100; 389; 390; 399; 400; 409; 489; 490; 498; 499]%nat.

Definition sample_states : list state :=
  flat_map (fun l => flat_map (fun c => map (fun k => mkState l c k) [0; 3]%nat)
                       sample_counts) [false; true].

Definition amounts : list nat := [0; 1; 9; 10; 100; 101; 499; 500; 1000]%nat.

Definition sample_events : list event :=
  map Add amounts ++ map Sub amounts ++ [Reset; Lock; Unlock].

Definition step_json (s : state) (e : event) : json :=
  JObj [("from", snap_json (enc s)); ("event", event_json e);
        ("to", snap_json (enc (update s e)));
        ("meta", JObj [("locked", JBool (locked (update s e)))]);
        ("can", JBool (enabled s e))].

(** ** Pseudo-random traces *)

Definition lcg (x : N) : N := N.modulo (1103515245 * x + 12345) 2147483648.

Definition pick (x : N) : event :=
  match N.to_nat (N.modulo (N.div x 65536) 16) with
  | 0 | 1 | 2 | 3 => Add 100
  | 4 | 5 => Add 10
  | 6 => Add 1
  | 7 => Add 250
  | 8 => Sub 10
  | 9 => Sub 100
  | 10 => Sub 1
  | 11 => Lock
  | 12 => Unlock
  | 13 => Reset
  | 14 => Add 0
  | _ => Add 499
  end%nat.

Fixpoint gen (k : nat) (x : N) : list event :=
  match k with
  | O => []
  | S k' => let x' := lcg x in pick x' :: gen k' x'
  end.

Fixpoint states_after (s : state) (es : list event) : list state :=
  match es with
  | [] => []
  | e :: es' => let s' := update s e in s' :: states_after s' es'
  end.

Definition trace_json (es : list event) : json :=
  JObj [("events", JArr (map event_json es));
        ("snapshots", JArr (map (fun s => snap_json (enc s)) (states_after initial es)))].

Definition trace_events : list (list event) := map (fun i => gen 60 (N.of_nat i)) (seq 1 20).

Lemma oracle_events_admitted :
  forallb (fun e => N.leb (N.of_nat (amount e)) payload_max)
    (sample_events ++ concat trace_events) = true.
Proof. vm_compute. reflexivity. Qed.

Definition schema_json : json :=
  JObj [("payloadMax", JStr (ndigits payload_max));
        ("types", JObj (map (fun kv => (fst kv, JStr (match snd kv with
                                                      | PNone => "none"
                                                      | PNat _ => "nat"
                                                      end)))
                         (cm_events counter)))].

Definition counter_oracle : json :=
  JObj [("steps", JArr (flat_map (fun s => map (step_json s) sample_events) sample_states));
        ("traces", JArr (map trace_json trace_events));
        ("schema", schema_json)].

Lemma counter_oracle_safe : json_safe counter_oracle = true.
Proof. vm_compute. reflexivity. Qed.

Definition counter_oracle_text : string := print counter_oracle.
