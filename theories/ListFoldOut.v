(** * Outputs for the Foldkit list: the TypeScript module and its oracle.

    [list_ts] is the printed program.  [list_fold_oracle] is computed from
    the model in Fold.v ([f_update], [f_can]), whose agreement with
    ListUI.v is proved in ListFold.v.  The Node tests run the printed
    module against it:

    - [steps]: every reachable state (each subset of the three starting
      items, with nothing or one of them selected), and some that are not
      (ids 0 and [max_id], a repeated id, a selection that is not in the
      list), times sampled messages (each item id, ids that are absent or
      over the maximum, delete and reset with and without [n], missing
      payloads, the save's result messages, unknown tags), with the
      expected model, commands, and [can];
    - [traces]: pseudo-random message sequences from the initial model,
      with the expected model and commands after every message;
    - [restores]: stored records, each with the model the app starts from.
      [restore] of [decode_saved]: valid saves come back as they are, and
      anything else gives the initial model: a selection that is not one
      of the ids, a repeated id, an id over [max_id], a missing or
      mistyped field, or something that is not a record.  Extra keys are
      dropped.  Labels with characters the printer cannot print (the
      double quote, the backslash, anything outside printable ASCII) are
      in the Node tests instead;
    - [init] and [schema]: the initial model, the store key, the command,
      the saved fields, and the bounds and tags the payload and fuzz tests
      need, and [safeChars], the character codes below 128 that
      [safe_char] accepts, which the tests check the label pattern
      against. *)

From Stdlib Require Import String List NArith Ascii.
From VerifiedListUI Require Import XState XStateCtx CtxJs Json Fold FoldTs FoldOut.
From VerifiedListUI Require CounterOut.
From VerifiedListUI Require Import ListUI ListFold.
Import ListNotations.
Open Scope list_scope.
Open Scope string_scope.

Definition list_ts : string :=
  ts_module "Generated by Rocq from theories/ListFold.v (printer: theories/FoldTs.v). Do not edit."
    list_program.

(** ** Sampled steps *)

Fixpoint subsets {A} (l : list A) : list (list A) :=
  match l with
  | [] => [[]]
  | x :: l' => let r := subsets l' in map (cons x) r ++ r
  end.

(** The 20 states reachable from [initial]. *)
Definition reachable : list state :=
  flat_map (fun its => mkState its None :: map (fun it => mkState its (Some (item_id it))) its)
    (subsets (items initial)).

Definition odd_states : list state :=
  [mkState [mkItem 0 "Zero"; mkItem 1000 "Max"] (Some 1000);
   mkState [mkItem 0 "Zero"; mkItem 1000 "Max"] (Some 0);
   mkState [mkItem 7 "Same"; mkItem 7 "Same"] (Some 7);
   mkState [alpha] (Some 9);
   mkState [] (Some 2)].

Definition sample_models : list fmodel := map enc (reachable ++ odd_states).

Definition sample_msgs : list jevent :=
  map (fun n => ("ClickedItem", PayNat n)) [0; 1; 2; 3; 4; 7; 1000; 1001]%nat ++
  [("ClickedItem", PayOther);
   ("ClickedDelete", PayOther); ("ClickedDelete", PayNat 1);
   ("ClickedReset", PayOther); ("ClickedReset", PayNat 2);
   ("CompletedSaveList", PayOther); ("FailedSaveList", PayOther);
   ("Nope", PayNat 1); ("clickedItem", PayNat 1); ("", PayOther)].

(** ** Pseudo-random traces *)

Definition pick_msg (x : N) : jevent :=
  match N.to_nat (N.modulo (N.div x 65536) 12) with
  | 0 | 1 => msg (Select 1)
  | 2 | 3 => msg (Select 2)
  | 4 => msg (Select 3)
  | 5 | 6 | 7 => msg DeleteSelected
  | 8 => msg Reset
  | 9 => msg (Select 4)
  | 10 => ("ClickedItem", PayNat 1001)
  | _ => ("ClickedDelete", PayNat 3)
  end%nat.

Fixpoint gen_msgs (k : nat) (x : N) : list jevent :=
  match k with
  | O => []
  | S k' => let x' := CounterOut.lcg x in pick_msg x' :: gen_msgs k' x'
  end.

Definition trace_msgs : list (list jevent) := map (fun i => gen_msgs 60 (N.of_nat i)) (seq 1 20).

(** ** Restoring *)

Definition item_json (id : nat) (label : string) : json :=
  JObj [("id", JNum id); ("label", JStr label)].

Definition stored (sel : json) (its : list json) : json :=
  JObj [("selected", sel); ("items", JArr its)].

Definition restore_cases : list json :=
  map (fun s => model_json (enc s)) reachable ++
  [(* Valid: the extremes, an empty list, any printable label. *)
   model_json (enc (mkState [mkItem 0 "Zero"; mkItem 1000 "Max"] (Some 1000)));
   stored JNull [];
   stored (JNum 5) [item_json 5 ""; item_json 9 " a ~ {[(<'!#$%&*+,-./:;=>?@^_`|}])> "];
   (* Valid, with the keys in another order and extra keys dropped. *)
   JObj [("items", JArr [item_json 2 "Beta"]); ("selected", JNum 2)];
   JObj [("selected", JNull); ("items", JArr [JObj [("label", JStr "A"); ("id", JNum 4); ("done", JBool true)]]);
         ("extra", JNum 1)];
   (* The selection is not one of the ids. *)
   model_json (enc (mkState [alpha] (Some 9)));
   model_json (enc (mkState [] (Some 2)));
   (* A repeated id. *)
   model_json (enc (mkState [mkItem 7 "Same"; mkItem 7 "Same"] (Some 7)));
   stored JNull [item_json 1 "A"; item_json 2 "B"; item_json 1 "C"];
   (* An id over the maximum. *)
   stored JNull [item_json 1001 "Big"];
   stored (JNum 1001) [item_json 1 "A"];
   (* Missing or mistyped fields. *)
   JObj [("selected", JNull)];
   JObj [("items", JArr [item_json 1 "A"])];
   stored (JStr "1") [item_json 1 "A"];
   stored (JBool true) [item_json 1 "A"];
   stored (JArr []) [];
   JObj [("selected", JNull); ("items", JObj [])];
   JObj [("selected", JNull); ("items", JNull)];
   stored JNull [JNum 1];
   stored JNull [JObj [("id", JNum 1)]];
   stored JNull [JObj [("label", JStr "A")]];
   stored JNull [JObj [("id", JStr "1"); ("label", JStr "A")]];
   stored JNull [JObj [("id", JNum 1); ("label", JNum 1)]];
   stored JNull [JObj [("id", JNum 1); ("label", JNull)]];
   stored JNull [JArr [JNum 1; JStr "A"]];
   (* Not a record. *)
   JObj []; JArr []; JNum 5; JBool true; JStr "list"; JNull].

Definition restore_json (j : json) : json :=
  JObj [("stored", j);
        ("model", model_json (restore list_program (decode_saved list_program j)))].

(** ** The oracle *)

Definition safe_codes : list nat := filter (fun n => safe_char (ascii_of_nat n)) (seq 0 128).

Definition schema_json : json :=
  JObj [("key", JStr (p_key list_program));
        ("command", JStr (p_cmd list_program));
        ("saved", JArr (map JStr (p_saved list_program)));
        ("maxes", maxes_json list_program);
        ("tags", tags_json list_program);
        ("safeChars", JArr (map JNum safe_codes))].

Definition list_fold_oracle : json :=
  JObj [("init", model_json (p_init list_program));
        ("steps", JArr (flat_map (fun m => map (step_json list_program m) sample_msgs) sample_models));
        ("traces", JArr (map (trace_json list_program) trace_msgs));
        ("restores", JArr (map restore_json restore_cases));
        ("schema", schema_json)].

Lemma list_fold_oracle_safe : json_safe list_fold_oracle = true.
Proof. vm_compute. reflexivity. Qed.

Definition list_fold_oracle_text : string := print list_fold_oracle.
