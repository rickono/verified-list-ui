(** * Outputs for the Foldkit counter: the TypeScript module and its oracle.

    [counter_ts] is the printed program.  [counter_fold_oracle] is computed
    from the model in Fold.v ([f_update], [f_can], [restore]), whose
    agreement with Counter.v is proved in CounterFold.v.  The Node tests
    run the printed module against it:

    - [steps]: sampled models (both lock states, counts around every
      boundary, two amount-field states) times sampled messages (counter
      events with amounts around the cap, amount-field messages, command
      results, missing payloads, unknown tags), with the expected model,
      commands, and [can];
    - [traces]: pseudo-random message sequences from the initial model,
      with the expected model and commands after every message;
    - [restores]: stored JSON values (valid saves, out-of-range counts,
      missing or mistyped fields, extra keys, non-objects) and the model
      [restore] gives for each;
    - [init] and [schema]: the initial model, and the bounds and tags the
      payload and fuzz tests need. *)

From Stdlib Require Import String List NArith.
From VerifiedListUI Require Import XState XStateCtx CtxJs Json Fold FoldTs FoldOut.
From VerifiedListUI Require CounterOut.
From VerifiedListUI Require Import Counter CounterFold.
Import ListNotations.
Open Scope list_scope.
Open Scope string_scope.

Definition counter_ts : string :=
  ts_module "Generated by Rocq from theories/CounterFold.v (printer: theories/FoldTs.v). Do not edit."
    counter_program.

(** ** Sampled steps *)

Definition sample_models : list fmodel :=
  flat_map (fun s => [enc s 250 true; enc s 7 false]) CounterOut.sample_states.

Definition sample_msgs : list jevent :=
  map msg CounterOut.sample_events ++
  [("ChangedAmount", PayNat 0); ("ChangedAmount", PayNat 4321); ("ClearedAmount", PayOther);
   ("CompletedSaveCounter", PayOther); ("FailedSaveCounter", PayOther);
   ("ClickedAdd", PayOther); ("ClickedSubtract", PayOther); ("ChangedAmount", PayOther);
   ("ClickedReset", PayNat 3); ("ClickedLock", PayNat 0);
   ("Nope", PayNat 1); ("clickedAdd", PayNat 1); ("", PayOther)].

(** ** Pseudo-random traces *)

Definition pick_msg (x : N) : jevent :=
  match N.to_nat (N.modulo (N.div x 65536) 20) with
  | 0 | 1 | 2 | 3 => msg (Add 100)
  | 4 | 5 => msg (Add 10)
  | 6 => msg (Add 1)
  | 7 => msg (Add 250)
  | 8 => msg (Sub 10)
  | 9 => msg (Sub 100)
  | 10 => msg (Sub 1)
  | 11 => msg Lock
  | 12 => msg Unlock
  | 13 => msg Reset
  | 14 => msg (Add 0)
  | 15 => msg (Add 499)
  | 16 => ("ChangedAmount", PayNat 42)
  | 17 => ("ClearedAmount", PayOther)
  | 18 => ("CompletedSaveCounter", PayOther)
  | _ => ("ClickedAdd", PayOther)
  end%nat.

Fixpoint gen_msgs (k : nat) (x : N) : list jevent :=
  match k with
  | O => []
  | S k' => let x' := CounterOut.lcg x in pick_msg x' :: gen_msgs k' x'
  end.

Definition trace_msgs : list (list jevent) := map (fun i => gen_msgs 60 (N.of_nat i)) (seq 1 20).

(** ** Restoring *)

Definition restore_cases : list json :=
  map (fun s => model_json (senc s)) CounterOut.sample_states ++
  [JObj [("locked", JBool false); ("count", JNum 500); ("changes", JNum 0)];
   JObj [("locked", JBool true); ("count", JNum 1000); ("changes", JNum 2)];
   JObj [("locked", JBool true); ("count", JNum 499); ("changes", JNum 7);
         ("amount", JNum 3); ("amountOk", JBool false); ("extra", JNum 1)];
   JObj [("count", JNum 5); ("changes", JNum 1)];
   JObj [("locked", JStr "yes"); ("count", JNum 5); ("changes", JNum 1)];
   JObj [("locked", JBool false); ("count", JNum 5)];
   JObj [("locked", JBool false); ("count", JStr "5"); ("changes", JNum 1)];
   JObj [("locked", JBool false); ("count", JArr []); ("changes", JNum 1)];
   JObj []; JArr []; JNum 5; JBool true; JStr "counter"].

Definition restore_json (j : json) : json :=
  JObj [("stored", j);
        ("model", model_json (restore counter_program (decode_saved counter_program j)))].

(** ** The oracle *)

Definition schema_json : json :=
  JObj [("payloadMax", JStr (ndigits payload_max));
        ("limit", JNum limit);
        ("key", JStr (p_key counter_program));
        ("command", JStr (p_cmd counter_program));
        ("saved", JArr (map JStr (p_saved counter_program)));
        ("maxes", maxes_json counter_program);
        ("tags", tags_json counter_program)].

Definition counter_fold_oracle : json :=
  JObj [("init", model_json (p_init counter_program));
        ("steps", JArr (flat_map (fun m => map (step_json counter_program m) sample_msgs) sample_models));
        ("traces", JArr (map (trace_json counter_program) trace_msgs));
        ("restores", JArr (map restore_json restore_cases));
        ("schema", schema_json)].

Lemma counter_fold_oracle_safe : json_safe counter_fold_oracle = true.
Proof. vm_compute. reflexivity. Qed.

Definition counter_fold_oracle_text : string := print counter_fold_oracle.
