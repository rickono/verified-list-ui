(** * The .fold sources build the hand-written programs.

    [CounterApp] and [ListApp] are generated by fold/ from
    foldkit-web/src/counter.fold and list.fold.  Each is equal, by
    computation, to the program defined by hand in the theory, so every
    theorem proved about [counter_program] and [list_program] also holds
    for the program the .fold file describes. *)

From VerifiedListUI Require Import Fold FoldTs CounterFold ListFold.
From FoldApps Require CounterApp ListApp.

Lemma counter_same : CounterApp.app = counter_program.
Proof. reflexivity. Qed.

Lemma list_same : ListApp.app = list_program.
Proof. reflexivity. Qed.

(** So the modules Rocq prints for them differ only in the header line,
    which names the source file and its hash. *)
Lemma counter_ts_same : exists header, CounterApp.ts = FoldTs.ts_module header counter_program.
Proof. eexists. unfold CounterApp.ts. rewrite counter_same. reflexivity. Qed.

Lemma list_ts_same : exists header, ListApp.ts = FoldTs.ts_module header list_program.
Proof. eexists. unfold ListApp.ts. rewrite list_same. reflexivity. Qed.
