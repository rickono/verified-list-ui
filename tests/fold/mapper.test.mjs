// fold/mapper, the TypeScript 7.1 content mapper for .fold files.
//
// The first tests speak the protocol (microsoft/TypeScript#63800) to
// fold/mapper/server.mjs directly.  The last runs tsc 7.1 on
// tests/fold/fixture, whose level.fold has a rule that can break its
// invariant, and checks that tsc reports the failed proof on that rule.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const fixture = resolve("tests/fold/fixture");
const config = resolve(fixture, "tsconfig.json");
const level = resolve(fixture, "src/level.fold");
const levelSrc = readFileSync(level, "utf8");

// A JSON-RPC client over the mapper's stdio, with Content-Length framing.
function mapper() {
  const p = spawn("node", ["server.mjs"], { cwd: resolve("fold/mapper"), stdio: ["pipe", "pipe", "inherit"] });
  const waiting = new Map();
  let buf = Buffer.alloc(0);
  let next = 1;
  p.stdout.on("data", (chunk) => {
    buf = Buffer.concat([buf, chunk]);
    for (;;) {
      const sep = buf.indexOf("\r\n\r\n");
      if (sep < 0) return;
      const len = Number(/Content-Length: (\d+)/.exec(buf.subarray(0, sep).toString())[1]);
      if (buf.length < sep + 4 + len) return;
      const msg = JSON.parse(buf.subarray(sep + 4, sep + 4 + len).toString("utf8"));
      buf = buf.subarray(sep + 4 + len);
      waiting.get(msg.id)(msg);
      waiting.delete(msg.id);
    }
  });
  const call = (method, params) =>
    new Promise((ok, fail) => {
      const id = next++;
      waiting.set(id, (m) => (m.error ? fail(new Error(m.error.message)) : ok(m.result)));
      const body = Buffer.from(JSON.stringify({ jsonrpc: "2.0", id, method, params }));
      p.stdin.write(`Content-Length: ${body.length}\r\n\r\n`);
      p.stdin.write(body);
    });
  const exited = new Promise((r) => p.on("exit", r));
  const close = () => {
    p.stdin.end();
    return exited;
  };
  return { call, close };
}

const spanOf = (src, d) => src.slice(d.start, d.start + d.length);

test("the mapper prints the module, maps it, and reports the failed proof", async () => {
  const m = mapper();
  try {
    assert.deepEqual(await m.call("initialize", { positionEncodings: ["utf-8", "utf-16"] }), {
      positionEncoding: "utf-16",
      diagnosticSource: "fold",
    });
    const opened = await m.call("openProject", { configFileName: config, projectHandle: "p", compilerOptions: {} });
    assert.match(opened.configIdentity, /^[0-9a-f]{64}$/);
    assert.equal(opened.optionDiagnostics, undefined);
    assert.ok(opened.watchedFiles.some((f) => f.endsWith("FoldAuto.vo")));
    assert.ok(opened.watchedFiles.some((f) => f.endsWith("emit-v.mjs")));

    const r = await m.call("transform", { fileName: level, content: levelSrc, projectHandle: "p" });
    assert.equal(r.extension, ".ts");
    assert.match(r.text, /^\/\/ Generated by Rocq from src\/level\.fold /);
    assert.match(r.text, /export const Message = defineMessageUnion/);
    assert.equal(r.diagnostics.length, 1, JSON.stringify(r.diagnostics, null, 2));
    const [d] = r.diagnostics;
    assert.equal(d.code, 3);
    assert.equal(spanOf(levelSrc, d), "if (model.level + n <= cap)");
    assert.match(d.messageText, /^belowCap might not hold after this branch of Raised\./);
    // The switch case for Raised maps to the rule's name.
    const v = r.text.indexOf('case "Raised"') + 6;
    const hit = r.mappings.find(([vs]) => vs === v);
    assert.ok(hit);
    assert.equal(levelSrc.slice(hit[2], hit[2] + hit[3]), "Raised");

    // While the file does not parse, the last printed module stands in, unmapped.
    const broken = await m.call("transform", { fileName: level, content: "model {", projectHandle: "p" });
    assert.equal(broken.text, r.text);
    assert.deepEqual(broken.mappings, []);
    assert.deepEqual(broken.diagnostics.map((x) => x.code), [1]);
    await m.call("closeProject", { projectHandle: "p" });
  } finally {
    await m.close();
  }
});

test("the mapper checks its options", async () => {
  const m = mapper();
  try {
    await m.call("initialize", { positionEncodings: ["utf-16"] });
    const opened = await m.call("openProject", {
      configFileName: config,
      projectHandle: "p",
      compilerOptions: {},
      options: { rocq: 3, theories: "nowhere", lean: true },
    });
    assert.deepEqual(
      opened.optionDiagnostics.map((d) => [d.code, d.path.join(".")]),
      [
        [7, "rocq"],
        [7, "lean"],
        [7, "theories"],
      ],
    );
    assert.match(opened.optionDiagnostics[2].messageText, /The compiled theory is not at .*tests\/fold\/fixture\/nowhere/);
  } finally {
    await m.close();
  }
});

test("the mapper answers in UTF-8 offsets when asked to", async () => {
  const m = mapper();
  try {
    assert.equal((await m.call("initialize", { positionEncodings: ["utf-8"] })).positionEncoding, "utf-8");
    await m.call("openProject", { configFileName: config, projectHandle: "p", compilerOptions: {} });
    const src = `// Ünïcödé → before the rule\n${levelSrc}`;
    const r = await m.call("transform", { fileName: level, content: src, projectHandle: "p" });
    const bytes = Buffer.from(src, "utf8");
    const [d] = r.diagnostics;
    assert.equal(bytes.subarray(d.start, d.start + d.length).toString("utf8"), "if (model.level + n <= cap)");
    for (const [, , os, ol, kind] of r.mappings) {
      assert.ok(os + ol <= bytes.length);
      if (kind === 0) assert.ok(!bytes.subarray(os, os + ol).toString("utf8").includes("�"));
    }
  } finally {
    await m.close();
  }
});

test("tsc 7.1 reports the failed proof on the rule", () => {
  const r = spawnSync("node", [resolve("node_modules/typescript-7.1/bin/tsc"), "-p", fixture, "--runExternalCode", "--pretty", "false"], {
    encoding: "utf8",
  });
  const out = r.stdout + r.stderr;
  assert.equal(r.status, 2, out);
  assert.match(out, /level\.fold\(11,3\): error fold3: belowCap might not hold after this branch of Raised/);
});
